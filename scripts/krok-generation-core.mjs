export function makeOptions(item, section, questionId, variant) {
  const excludedDistractors = new Set();
  if (item.correct === "Внутрішньовенний імуноглобулін") {
    excludedDistractors.add("Плазмаферез");
  }
  const pool = distractorPoolForItem(item, section).filter(
    (option) => option !== item.correct && !excludedDistractors.has(option)
  );
  const selected = [];
  let cursor = variant % pool.length;
  while (selected.length < 4) {
    const candidate = pool[cursor % pool.length];
    if (!selected.includes(candidate)) {
      selected.push(candidate);
    }
    cursor += 1;
  }
  const correctIndex = variant % 5;
  const texts = selected.slice();
  texts.splice(correctIndex, 0, item.correct);
  return texts.map((text, index) => ({
    id: `${questionId}-${String.fromCharCode(97 + index)}`,
    sourceLetter: String.fromCharCode(97 + index),
    text
  }));
}

export function deterministicShuffle(items, seed) {
  const next = items.slice();
  let value = seed >>> 0;
  const random = () => {
    value += 0x6d2b79f5;
    let t = value;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  for (let index = next.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [next[index], next[swapIndex]] = [next[swapIndex], next[index]];
  }
  return next;
}

export function createGeneratedEntries({
  targets = sectionTargets,
  bookletIndex,
  variantOffset = 0,
  avoidFamilyRepeats = false,
  familyKeyForItem = (item) => item.correct
}) {
  const rawQuestions = [];
  const usedFamilyKeysBySection = new Map();
  let withinBooklet = 0;
  let longRemaining = 6;
  let directRemaining = 6;

  for (const [section, count] of targets) {
    const availableConcepts = conceptsBySection.get(section);
    if (!availableConcepts?.length) {
      throw new Error(`No concepts for section ${section}`);
    }
    const usedFamilyKeys = usedFamilyKeysBySection.get(section) ?? new Set();
    usedFamilyKeysBySection.set(section, usedFamilyKeys);
    for (let sectionIndex = 0; sectionIndex < count; sectionIndex += 1) {
      const startConceptIndex = (bookletIndex * 3 + sectionIndex) % availableConcepts.length;
      let item = null;
      for (let offset = 0; offset < availableConcepts.length; offset += 1) {
        const candidate = availableConcepts[(startConceptIndex + offset) % availableConcepts.length];
        const familyKey = familyKeyForItem(candidate);
        if (!avoidFamilyRepeats || !usedFamilyKeys.has(familyKey)) {
          item = candidate;
          usedFamilyKeys.add(familyKey);
          break;
        }
      }
      if (!item) {
        throw new Error(`No non-repeating concept family for section ${section}`);
      }
      const variant = variantOffset + bookletIndex * 151 + withinBooklet * 11 + sectionIndex;
      const profile = profileFor(item, ageFor(bookletIndex, withinBooklet), variant);
      const directPreferred = prefersDirectStem(item);
      let style = "medium";
      if (directPreferred) {
        style = "direct";
      } else if (longRemaining > 0 && (withinBooklet % 19 === 0 || withinBooklet > 90)) {
        style = "long";
        longRemaining -= 1;
      } else if (directRemaining > 0 && withinBooklet % 17 === 3) {
        style = "direct";
        directRemaining -= 1;
      }
      const stem =
        style === "long"
          ? makeLongStem(item, profile, variant)
          : style === "direct"
            ? makeDirectStem(item, variant, withinBooklet, bookletIndex)
            : makeMediumStem(item, profile, variant, withinBooklet);
      rawQuestions.push({
        item,
        stem: stem.replace(/\.\./g, "."),
        variant,
        section,
        provisionalIndex: withinBooklet
      });
      withinBooklet += 1;
    }
  }

  return rawQuestions;
}

export function materializeGeneratedQuestion(entry, bookletId, sourceNumber, questionId) {
  const options = makeOptions(entry.item, entry.section, questionId, entry.variant);
  const correctOption = options.find((option) => option.text === entry.item.correct);
  return {
    id: questionId,
    bookletId,
    sourceNumber,
    contentSection: `${entry.section}.0.0.0`,
    contentCode: entry.item.code,
    text: entry.stem,
    options,
    correctOptionId: correctOption.id,
    explanation: makeExplanation(entry.item)
  };
}

export function createGeneratedBooklet({
  booklet,
  bookletIndex,
  targets = sectionTargets,
  kind = "training",
  sourceFile = "Структура_змісту_Кр_3_Неврологія.pdf",
  shuffleSeed = 2026 + bookletIndex * 101,
  variantOffset = 0
}) {
  const rawQuestions = createGeneratedEntries({ targets, bookletIndex, variantOffset });
  const shuffled = deterministicShuffle(rawQuestions, shuffleSeed);
  const questions = shuffled.map((entry, index) => {
    const sourceNumber = index + 1;
    const questionId = `${booklet.id}-${String(sourceNumber).padStart(3, "0")}`;
    return materializeGeneratedQuestion(entry, booklet.id, sourceNumber, questionId);
  });

  return {
    id: booklet.id,
    kind,
    title: booklet.title,
    sourceFile,
    questions
  };
}
